test('after 02: anon, authenticated and PUBLIC cannot read, write, delete, truncate or touch sequences', async () => withDb(async db => {
  const before = await counts(db)
  await runAs(db, 'site_owner', APPLY)
  for (const role of PUBLIC_ROLES) {
    for (const table of TABLES) {
      await denied(tryAs(db, role, `SELECT * FROM public.${table}`), `${role} SELECT ${table}`)
      await denied(tryAs(db, role, `DELETE FROM public.${table}`), `${role} DELETE ${table}`)
      await denied(tryAs(db, role, `UPDATE public.${table} SET ${table === 'schema_migrations' ? 'name' : table === 'mangas' ? 'title' : table === 'pages_backup_cloudinary_before_public_id' ? 'url' : 'id'} = ${table === 'chapters' || table === 'pages' || table === 'comments' ? 'id' : "'x'"}`), `${role} UPDATE ${table}`)
      await denied(tryAs(db, role, `TRUNCATE public.${table} CASCADE`), `${role} TRUNCATE ${table}`)
    }
    await denied(tryAs(db, role, "INSERT INTO comments(manga_id, author_name, content) VALUES ('luz','Invasor','x')"), `${role} INSERT`)
    await denied(tryAs(db, role, "SELECT nextval('comments_id_seq')"), `${role} nextval`)
    await denied(tryAs(db, role, "SELECT setval('pages_id_seq', 1)"), `${role} setval`)
  }
  assert.deepEqual(await counts(db), before, 'no fixture row changed')
  const diag = await diagnose(db)
  assert.equal(diag.protegido, true)
  assert.ok(diag.tabelas.every(table => table.rls === true && table.dono === 'site_owner'))
  assert.ok(diag.privilegios_publicos_tabelas.every(row => row.privilegios === null))
  assert.ok((diag.privilegios_publicos_sequencias ?? []).every(row => row.privilegios === null))
  await runAs(db, 'site_owner', APPLY) // idempotent
  assert.equal((await diagnose(db)).protegido, true)
}))

