const withDb = async fn => { const db = await freshDb(); try { await fn(db) } finally { await db.close() } }

test('scripts: 01 is one read-only SELECT; 02/03/04 are transactional and never touch rows', () => {
  const code = sql => sql.replace(/--[^\n]*/g, '')
  const diag = code(DIAG).trim().split(';').map(s => s.trim()).filter(Boolean)
  assert.equal(diag.length, 1); assert.match(diag[0], /^SELECT\b/)
  for (const word of ['INSERT', 'UPDATE', 'DELETE', 'CREATE', 'ALTER', 'DROP', 'GRANT', 'REVOKE', 'TRUNCATE', 'COPY', 'SET']) {
    assert.doesNotMatch(diag[0], new RegExp(`\\b${word}\\b(?! *['"])`, 'i'), `diagnostic contains ${word}`)
  }
  assert.doesNotMatch(diag[0], /client_addr|passwd|rolpassword/, 'no IPs or password columns')
  for (const [name, sql] of [['02', APPLY], ['03', BACKEND], ['04', REVERT]]) {
    const body = code(sql)
    assert.match(body.trim(), /^BEGIN;[\s\S]*COMMIT;$/, `${name} is one transaction`)
    assert.doesNotMatch(body, /\bDELETE\s+FROM\b|\bINSERT\s+INTO\b|\bUPDATE\s+public\.|\bTRUNCATE\s+(TABLE\s+)?public|\bDROP\s+/i, `${name} never changes rows or drops objects`)
  }
  assert.doesNotMatch(code(APPLY), /\bGRANT\b/, '02 only revokes')
})

